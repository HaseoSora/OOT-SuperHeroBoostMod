"""Developer step: write core/gd_index.h, the GameData Bool indices the buttonMapping reads.

  GD_IS_CHILDHOOD          index of Sequence_IsChildhood (1 while Link is a child)
  GD_S64_EQUIP_WEAPON / _SHIELD  String64 indices of the equipped sword / shield (icon names)
  GD_BOX_CHILD / _ADULT    Enum indices of PlayerStatus.AssignableItem.Child / .Adult (the item box), GD_EMPTY_HASH
  GD_ISGET[]               {murmur3("IsGet.<item>"), index} for every IsGet.* Bool, sorted by hash
  GD_ACTOR_BOX[]           {murmur3(item actor name), murmur3(its item-box value)}, sorted (RSDB PouchActorInfo)

Bool records are in GameDataList definition order (see the devtool's gdlive.py), so these indices belong to one
GameDataList (Product.110, game 1.1.1). Needs the devtool's definition cache and names.tsv (names_build.py).
"""
import pickle
import sys
from pathlib import Path

DEVTOOL = Path(r"F:\project\oot\vendor\devtool\oot-remake-devtool-main")
sys.path.insert(0, str(DEVTOOL))
import gamedata  # noqa: E402
import catalog  # noqa: E402

ROMFS = Path(r"F:/switch2/Longshot/romfs")

OUT = Path(__file__).resolve().parent.parent / "core" / "gd_index.h"


def main():
    cache = sorted((DEVTOOL / "cache").glob("gdl2_*.pkl"))[-1]
    defs, meta = pickle.load(open(cache, "rb"))
    bools = [h for h, d in defs.items() if d.type == "Bool"]
    index = {h: i for i, h in enumerate(bools)}
    names = {}
    for line in open(DEVTOOL / "names.tsv", encoding="utf-8"):
        if "\t" in line:
            h, n = line.rstrip("\n").split("\t", 1)
            names[int(h, 16)] = n
    child = gamedata.mmh("Sequence_IsChildhood")
    enums = [h for h, d in defs.items() if d.type == "Enum"]
    s64 = [h for h, d in defs.items() if d.type == "String64"]
    isget = sorted((h, index[h]) for h, n in names.items() if n.startswith("IsGet.") and h in index)
    lines = [
        "/* generated by tools/gen_gd_index.py from %s: do not edit */" % meta.get("file", cache.name),
        "#define GD_IS_CHILDHOOD %d" % index[child],
        "#define GD_BOX_CHILD %d   /* Enum index of PlayerStatus.AssignableItem.Child */"
        % enums.index(gamedata.mmh("PlayerStatus.AssignableItem.Child")),
        "#define GD_BOX_ADULT %d" % enums.index(gamedata.mmh("PlayerStatus.AssignableItem.Adult")),
        "#define GD_S64_EQUIP_WEAPON %d   /* String64 index of PlayerStatus.EquipWeapon */"
        % s64.index(gamedata.mmh("PlayerStatus.EquipWeapon")),
        "#define GD_S64_EQUIP_SHIELD %d" % s64.index(gamedata.mmh("PlayerStatus.EquipShield")),
        "#define GD_EMPTY_HASH 0x%08Xu   /* the Enum value \"Empty\" */" % gamedata.mmh("Empty"),
        "#define GD_ISGET_N %d" % len(isget),
        "static const unsigned int GD_ISGET[GD_ISGET_N][2] = {",
    ]
    lines += ["    {0x%08Xu, %du}," % (h, i) for h, i in isget]
    lines.append("};")
    rows = catalog._rsdb(gamedata.RomFS(str(ROMFS)), str(ROMFS), "PouchActorInfo")
    box = sorted({(gamedata.mmh(r["__RowId"]), gamedata.mmh(r["AssignableItem"])) for r in rows
                  if r.get("AssignableItem") not in (None, "Empty") and r["__RowId"].startswith(("Item_", "Weapon_"))})
    lines.append("#define GD_ACTOR_BOX_N %d" % len(box))
    lines.append("static const unsigned int GD_ACTOR_BOX[GD_ACTOR_BOX_N][2] = {")
    lines += ["    {0x%08Xu, 0x%08Xu}," % (a, v) for a, v in box]
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="ascii")
    print("wrote", OUT, len(isget), "IsGet entries")


if __name__ == "__main__":
    main()
