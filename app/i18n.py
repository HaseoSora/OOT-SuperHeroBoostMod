def tr(lang: str, key: str, **kw) -> str:
    s = T.get(lang, T["en"]).get(key) or T["en"].get(key, key)
    try:
        return s.format(**kw)
    except Exception:
        return s


def system_lang() -> str:
    try:
        import ctypes
        lid = ctypes.windll.kernel32.GetUserDefaultUILanguage() & 0x3FF
        return LANGID.get(lid, "en")
    except Exception:
        import locale
        loc = (locale.getdefaultlocale()[0] or "en")[:2]
        return loc if loc in LANGS else "en"
